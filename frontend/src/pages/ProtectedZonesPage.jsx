import { useMemo, useState } from 'react'
import { Map, Plus, Trash2, Save, MousePointerClick, AlertTriangle } from 'lucide-react'
import { Badge, Button, Card, PageHeader } from '../components/ui/Primitives'
import { useAppData } from '../context/AppDataContext'

const cameraImages = {
  'Pond 1': 'https://images.unsplash.com/photo-1524704796725-9fc3044a58b2?auto=format&fit=crop&w=1200&q=80',
  'Pond 2': 'https://images.unsplash.com/photo-1544551763-46a013bb70d5?auto=format&fit=crop&w=1200&q=80',
  'Storage Area': 'https://images.unsplash.com/photo-1586528116311-ad8dd3c8310d?auto=format&fit=crop&w=1200&q=80',
  'Main Entrance': 'https://images.unsplash.com/photo-1464226184884-fa280b87c399?auto=format&fit=crop&w=1200&q=80',
}

export default function ProtectedZonesPage() {
  const { cameras, zones, addZone, updateZone, removeZone, addAlert, addIncident } = useAppData()
  const [selectedCameraId, setSelectedCameraId] = useState(cameras[0]?.id || '')
  const selectedCamera = cameras.find(c => c.id === selectedCameraId) || cameras[0]
  const cameraZones = zones.filter(z => z.cameraName === selectedCamera?.name)
  const [draftPoints, setDraftPoints] = useState([])
  const [zoneName, setZoneName] = useState('')

  const onFrameClick = (e) => {
    const rect = e.currentTarget.getBoundingClientRect()
    const x = ((e.clientX - rect.left) / rect.width) * 100
    const y = ((e.clientY - rect.top) / rect.height) * 100
    setDraftPoints(prev => [...prev, [Number(x.toFixed(2)), Number(y.toFixed(2))]])
  }

  const saveZone = () => {
    if (!selectedCamera) return
    if (draftPoints.length < 3) return
    const name = zoneName.trim() || `${selectedCamera.name} Protected Zone ${cameraZones.length + 1}`
    addZone({ name, cameraId: selectedCamera.id, cameraName: selectedCamera.name, points: draftPoints, enabled: true })
    setDraftPoints([])
    setZoneName('')
  }

  const simulateZoneEntry = (zone) => {
    const now = new Date().toISOString()
    const obj = Math.random() > 0.5 ? 'Person' : 'Dog'
    const conf = 90 + Math.floor(Math.random() * 8)
    addAlert({
      type: 'Unauthorized zone entry',
      camera: zone.cameraName,
      dateTime: now,
      confidence: conf,
      snapshot: obj === 'Person' ? 'person-pond1' : 'dog-pond2',
      description: `${obj} entered ${zone.name}. Event generated by protected-zone rule (simulated test).`,
      source: 'demo',
    })
    addIncident({
      eventType: obj === 'Person' ? 'Person intrusion' : 'Animal intrusion',
      object: obj,
      camera: zone.cameraName,
      dateTime: now,
      confidence: conf,
      zone: zone.name,
      snapshot: obj === 'Person' ? 'person-pond1' : 'dog-pond2',
      details: `Simulated zone-entry event: detected ${obj.toLowerCase()} crossed protected area boundary on ${zone.cameraName}.`,
      source: 'demo',
    })
  }

  return (
    <div>
      <PageHeader
        eyebrow="Geofenced protection"
        title="Protected zone management"
        subtitle="Draw and manage protected pond zones on camera frames. When a detected person or supported animal enters a zone, a security event is generated."
        actions={<Badge tone="info">Zone editor: demo marking interface</Badge>}
      />

      <div className="grid gap-4 xl:grid-cols-[1.2fr_0.8fr]">
        <Card>
          <div className="mb-4 flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
            <label className="block w-full sm:max-w-xs">
              <span className="mb-1.5 block text-sm font-medium text-slate-300">Camera frame</span>
              <select value={selectedCameraId} onChange={e => { setSelectedCameraId(e.target.value); setDraftPoints([]) }} className="w-full rounded-xl border border-white/10 bg-ocean-900/70 px-3 py-2.5 text-sm text-white outline-none focus:ring-2 focus:ring-aqua-400/30">
                {cameras.map(c => <option key={c.id} value={c.id}>{c.name} — {c.location}</option>)}
              </select>
            </label>
            <div className="flex flex-wrap gap-2">
              <Button variant="secondary" onClick={() => setDraftPoints(prev => prev.slice(0, -1))} disabled={!draftPoints.length}>Undo point</Button>
              <Button variant="secondary" onClick={() => setDraftPoints([])} disabled={!draftPoints.length}>Clear</Button>
            </div>
          </div>

          <div className="relative aspect-video cursor-crosshair overflow-hidden rounded-xl border border-white/10 bg-ocean-900" onClick={onFrameClick} title="Click to add polygon points">
            <img src={cameraImages[selectedCamera?.name] || cameraImages['Pond 1']} alt="Camera frame for zone selection" className="h-full w-full object-cover opacity-85" />
            <div className="absolute inset-0 bg-gradient-to-t from-ocean-950/40 to-transparent" />
            <svg className="absolute inset-0 h-full w-full" viewBox="0 0 100 100" preserveAspectRatio="none">
              {cameraZones.map(z => (
                <g key={z.id}>
                  <polygon points={z.points.map(p => p.join(',')).join(' ')} fill={z.enabled ? 'rgba(45,212,191,0.14)' : 'rgba(148,163,184,0.10)'} stroke={z.enabled ? 'rgba(45,212,191,0.95)' : 'rgba(148,163,184,0.6)'} strokeWidth="1.3" />
                </g>
              ))}
              {draftPoints.length > 0 && (
                <g>
                  <polyline points={draftPoints.map(p => p.join(',')).join(' ')} fill="none" stroke="rgba(56,189,248,0.95)" strokeWidth="1.3" />
                  {draftPoints.length >= 3 && <polygon points={draftPoints.map(p => p.join(',')).join(' ')} fill="rgba(56,189,248,0.14)" stroke="rgba(56,189,248,0.95)" strokeWidth="1.3" />}
                  {draftPoints.map((p, i) => <circle key={i} cx={p[0]} cy={p[1]} r="1.2" fill="#38bdf8" />)}
                </g>
              )}
            </svg>
            <div className="absolute left-3 top-3 rounded-lg bg-ocean-950/70 px-3 py-2 text-xs text-slate-200 ring-1 ring-white/10"><MousePointerClick className="mr-1 inline h-3.5 w-3.5 text-aqua-300" /> Click on the frame to mark protected area points ({draftPoints.length} points)</div>
          </div>

          <div className="mt-4 grid gap-3 sm:grid-cols-[1fr_auto] sm:items-end">
            <label className="block">
              <span className="mb-1.5 block text-sm font-medium text-slate-300">New zone name</span>
              <input value={zoneName} onChange={e => setZoneName(e.target.value)} placeholder={`${selectedCamera?.name || 'Camera'} Protected Zone`} className="w-full rounded-xl border border-white/10 bg-ocean-900/70 px-3 py-2.5 text-sm text-white outline-none focus:ring-2 focus:ring-aqua-400/30" />
            </label>
            <Button onClick={saveZone} disabled={draftPoints.length < 3}><Save className="h-4 w-4" /> Save zone</Button>
          </div>
          <p className="mt-2 text-xs text-slate-400">Add at least 3 points to define a polygon. Multiple protected pond zones are supported per camera.</p>
        </Card>

        <div className="space-y-4">
          <Card>
            <h3 className="font-display text-lg font-bold text-white">Configured zones</h3>
            <p className="mt-1 text-sm text-slate-400">Zones for {selectedCamera?.name}. Enable/disable, test events, or remove zones.</p>
            <div className="mt-4 space-y-3">
              {cameraZones.length === 0 ? <div className="rounded-xl border border-dashed border-white/15 bg-white/5 p-4 text-sm text-slate-400">No zones configured for this camera yet.</div> : cameraZones.map(zone => (
                <div key={zone.id} className="rounded-xl border border-white/10 bg-white/5 p-3">
                  <div className="flex items-start justify-between gap-2">
                    <div>
                      <div className="font-medium text-white">{zone.name}</div>
                      <div className="text-xs text-slate-400">{zone.cameraName} · {zone.points.length} points</div>
                    </div>
                    <Badge tone={zone.enabled ? 'success' : 'muted'}>{zone.enabled ? 'Enabled' : 'Disabled'}</Badge>
                  </div>
                  <div className="mt-3 flex flex-wrap gap-2">
                    <Button size="sm" variant="secondary" onClick={() => updateZone(zone.id, { enabled: !zone.enabled })}>{zone.enabled ? 'Disable' : 'Enable'}</Button>
                    <Button size="sm" onClick={() => simulateZoneEntry(zone)}><AlertTriangle className="h-4 w-4" /> Simulate zone entry</Button>
                    <Button size="sm" variant="danger" onClick={() => removeZone(zone.id)}><Trash2 className="h-4 w-4" /> Remove</Button>
                  </div>
                </div>
              ))}
            </div>
          </Card>

          <Card>
            <h3 className="font-display text-lg font-bold text-white">Zone event rule</h3>
            <ul className="mt-3 space-y-2 text-sm text-slate-300">
              <li>• When a detected <strong>Person</strong> or supported animal (e.g. <strong>Dog</strong>) intersects an enabled protected zone, a security event is generated.</li>
              <li>• Generated events create alerts and incident records with camera, timestamp, confidence, and snapshot context.</li>
              <li>• Use "Simulate zone entry" to demonstrate the end-to-end workflow without requiring live hardware.</li>
              <li>• Actual zone-intersection evaluation from live detections is performed by the backend detection service when connected.</li>
            </ul>
          </Card>
        </div>
      </div>
    </div>
  )
}